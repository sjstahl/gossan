"""Render the analysis report's blocks to PDF (reportlab) and Word (python-docx).

``build_analysis_report`` is the entry point behind ``gossan report --kind analysis``. Both files are
made from the same blocks (``analysis_content``), written to ``outputs/analysis_report.pdf`` /
``.docx`` with figures under ``outputs/report_assets/analysis/``, and logged to provenance with a
licence derived from the project's datasets (Access Only data make the report internal and mark
every page).
"""

